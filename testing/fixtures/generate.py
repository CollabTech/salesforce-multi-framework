#!/usr/bin/env python3
"""Generate the SMF-3 local file fixtures deterministically (DATA-04). Standard library only.

  python3 testing/fixtures/generate.py           # (re)write every fixture, then verify
  python3 testing/fixtures/generate.py --check   # verify files/hashes against manifest.json

Fixtures (logical IDs from testing/contract.json):
  MF-IMAGE-001       synthetic pump schematic PNG (<= 2 MiB), linked to MF-CASE-001 by the seed
  MF-FILE-DENIED     a different synthetic image, linked only to MF-CASE-002 by the seed
  MF-UPLOAD-INVALID  a .txt file and a > 5 MiB PNG for the image-only 5 MiB upload limit

Every image is drawn procedurally: no people, no customer data, no camera/EXIF/GPS metadata
(PNG chunks are IHDR, PLTE, tEXt Comment, IDAT, IEND only). Output is byte-identical on every
platform because the deflate stream uses stored blocks written here, not the zlib library's
compressor (whose output differs between zlib versions). Licence: generated by this
repository, dedicated to the public domain under CC0-1.0.

The > 5 MiB image is not committed (testing/fixtures/.gitignore); its size and SHA-256 are in
manifest.json, and this script regenerates the identical bytes.
"""
import argparse, hashlib, json, struct, sys, zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
MANIFEST = HERE / "manifest.json"
MIB = 1024 * 1024
