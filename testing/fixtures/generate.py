GENERATOR = "testing/fixtures/generate.py"

# ---------------------------------------------------------------- PNG writer (deterministic)

def _chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def _stored_zlib(raw):
    """zlib stream with stored (uncompressed) deflate blocks: identical bytes everywhere."""
    out = bytearray(b"\x78\x01")
    n = len(raw)
    pos = 0
    while True:
        block = raw[pos:pos + 65535]
        pos += len(block)
        final = 1 if pos >= n else 0
        out += bytes([final]) + struct.pack("<HH", len(block), len(block) ^ 0xFFFF) + block
        if final:
            break
    out += struct.pack(">I", zlib.adler32(raw) & 0xFFFFFFFF)
    return bytes(out)


def png_indexed(width, height, rows, palette, comment):
    """rows: list of bytes (palette indices, one byte per pixel)."""
    raw = b"".join(b"\x00" + r for r in rows)
    plte = b"".join(bytes(c) for c in palette)
    return (b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 3, 0, 0, 0))
            + _chunk(b"PLTE", plte)
            + _chunk(b"tEXt", b"Comment\x00" + comment.encode("latin-1"))
            + _chunk(b"IDAT", _stored_zlib(raw))
            + _chunk(b"IEND", b""))


def png_rgb(width, height, raw_rows, comment):
    raw = b"".join(b"\x00" + r for r in raw_rows)
    return (b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + _chunk(b"tEXt", b"Comment\x00" + comment.encode("latin-1"))
            + _chunk(b"IDAT", _stored_zlib(raw))
            + _chunk(b"IEND", b""))

