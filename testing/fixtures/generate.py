def build_image(variant, logical):
    w, h, rows, pal = draw_pump(variant)
    comment = (f"Synthetic fixture {logical} generated by {GENERATOR}; CC0-1.0; "
               "no people, customer data or location metadata")
    return png_indexed(w, h, rows, pal, comment)


def build_oversize():
    """> 5 MiB PNG: deterministic SHA-256 counter-mode noise, 1400x1400 RGB (~5.6 MiB)."""
    w = h = 1400
    rows = []
    seed = b"MF-UPLOAD-INVALID oversize v1"
    ctr = 0
    for _ in range(h):
        buf = bytearray()
        while len(buf) < w * 3:
            buf += hashlib.sha256(seed + ctr.to_bytes(8, "big")).digest()
            ctr += 1
        rows.append(bytes(buf[:w * 3]))
    return png_rgb(w, h, rows, "Synthetic fixture MF-UPLOAD-INVALID (oversize image) generated by "
                   f"{GENERATOR}; CC0-1.0; random noise, no people or location metadata")


