class Canvas:
    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.px = [bytearray([bg]) * w for _ in range(h)]

    def rect(self, x0, y0, x1, y1, c):
        for y in range(max(0, y0), min(self.h, y1)):
            row = self.px[y]
            row[max(0, x0):min(self.w, x1)] = bytes([c]) * (min(self.w, x1) - max(0, x0))

    def circle(self, cx, cy, r, c, inner=0):
        for y in range(max(0, cy - r), min(self.h, cy + r + 1)):
            for x in range(max(0, cx - r), min(self.w, cx + r + 1)):
                d = (x - cx) ** 2 + (y - cy) ** 2
                if inner * inner <= d <= r * r:
                    self.px[y][x] = c

    def text(self, x, y, s, c, scale=4):
        for ch in s:
            g = FONT[ch]
            for gy, line in enumerate(g):
                for gx, bit in enumerate(line):
                    if bit == "1":
                        self.rect(x + gx * scale, y + gy * scale, x + (gx + 1) * scale, y + (gy + 1) * scale, c)
            x += 6 * scale

    def rows(self):
        return [bytes(r) for r in self.px]

